const Lang = {
  get current() {
    try { return localStorage.getItem('cp_lang') === 'te' ? 'te' : 'en'; } catch { return 'en'; }
  },
  set(lang) {
    try { localStorage.setItem('cp_lang', lang); } catch { /* storage blocked */ }
    applyI18n();
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  },
};

function t(key, vars = {}) {
  const dict = I18N[Lang.current];
  let s = dict[key] ?? I18N.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

function applyI18n(root = document) {
  document.documentElement.lang = Lang.current === 'te' ? 'te' : 'en';
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('.lang-switch button').forEach((b) => b.classList.toggle('active', b.dataset.lang === Lang.current));
}

/** Adds an "English | తెలుగు" switch into every element with class "lang-switch". */
function mountLangSwitch() {
  document.querySelectorAll('.lang-switch').forEach((box) => {
    box.innerHTML = `<button type="button" data-lang="en">English</button><button type="button" data-lang="te">తెలుగు</button>`;
    box.querySelectorAll('button').forEach((b) => b.addEventListener('click', () => Lang.set(b.dataset.lang)));
  });
}

document.addEventListener('DOMContentLoaded', () => { mountLangSwitch(); applyI18n(); });
